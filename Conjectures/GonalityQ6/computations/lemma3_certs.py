"""Rank-0 certificates for the 130 divisors of Lemma 3 (Q_6 gonality proof).

For each D = 5*1_{N(0)} + R or D = 2*1_{S2(0)} + R (R = 0 or one chip), find a vertex q with
D(q) = 0 and the q-reduced divisor E ~ D with E(q) = 0. Output (q, z, order):
  z     : firing script with E = D - L z   (L = Laplacian of Q_6)
  order : a Dhar burning order of E from q (each vertex, when burned, has more burnt
          neighbours than chips), proving E is q-reduced.
Everything is re-checked here before writing; Lean re-checks it again (GonalityQ6.lean).
Independent implementation (does not reuse the proof's special.py / c2.c).
"""
N = 64
NB = [[v ^ (1 << k) for k in range(6)] for v in range(N)]

def burn(E, q):
    burnt = [False]*N; cnt = [0]*N; burnt[q] = True; order = [q]; i = 0
    while i < len(order):
        u = order[i]; i += 1
        for w in NB[u]:
            if not burnt[w]:
                cnt[w] += 1
                if cnt[w] > E[w]:
                    burnt[w] = True; order.append(w)
    return burnt, order

def reduce(D, q):
    E = D[:]; z = [0]*N
    while True:
        burnt, order = burn(E, q)
        if len(order) == N:
            return E, z, order
        U = [u for u in range(N) if not burnt[u]]
        out = {u: sum(1 for w in NB[u] if burnt[w]) for u in U}
        t = min(E[u] // out[u] for u in U if out[u] > 0)
        assert t >= 1
        for u in U:
            z[u] += t
        E = [D[u] - (6*z[u] - sum(z[w] for w in NB[u])) for u in range(N)]
        assert min(E) >= 0

def divisor(kind, extra):
    D = [0]*N
    for v in range(N):
        w = bin(v).count('1')
        if kind == 0 and w == 1: D[v] = 5
        if kind == 1 and w == 2: D[v] = 2
    if extra >= 0: D[extra] += 1
    return D

def check(D, q, z, order):
    E = [D[u] - (6*z[u] - sum(z[w] for w in NB[u])) for u in range(N)]
    assert all(e >= 0 for e in E) and E[q] == 0
    assert order[0] == q and sorted(order) == list(range(N))
    for i in range(1, N):
        u = order[i]; earlier = set(order[:i])
        assert E[u] < sum(1 for w in NB[u] if w in earlier)
    return True

certs = []
for kind in (0, 1):
    for extra in range(-1, N):
        D = divisor(kind, extra)
        for q in range(N):
            if D[q] != 0: continue
            E, z, order = reduce(D, q)
            if E[q] == 0:
                assert check(D, q, z, order)
                certs.append((kind, extra, q, z, order)); break
        else:
            raise SystemExit(f"no certificate for kind={kind} extra={extra}: positive rank?")
print(f"{len(certs)} certificates found and checked")
if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w") as f:
            f.write("/- Generated by computations/lemma3_certs.py. Do not edit. -/\n")
            f.write("import Conjectures.GonalityQ6.Basic\n\nnamespace GonalityQ6\n\n")
            f.write("/-- `(kind, extra, q, z, order)` for each of the 130 divisors. -/\n")
            f.write("def certs : List (ℕ × ℤ × ℕ × List ℤ × List ℕ) := [\n")
            rows = []
            for kind, extra, q, z, order in certs:
                rows.append(f"  ({kind}, {extra}, {q}, {z}, {order})")
            f.write(",\n".join(rows) + "]\n\nend GonalityQ6\n")
