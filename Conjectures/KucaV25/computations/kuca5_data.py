"""Data for the Lean proof that V(2,5) has exactly the even terms 2, 10, 52.

Generates V(2,5) up to N0 = 2(T+P) directly from the definition (independent of the C code),
checks that odd terms are P-periodic from T, writes the bit table and the witness pairs.
"""
import sys
T, P = 2131, 694
N0 = 2 * (T + P)
S = [False] * (N0 + 1)
S[2] = S[5] = True
for m in range(6, N0 + 1):
    r = sum(1 for a in range(1, m // 2 + 1) if S[a] and S[m - a])
    S[m] = (r == 1)
evens = [m for m in range(N0 + 1) if S[m] and m % 2 == 0]
assert evens == [2, 10, 52], evens
per = lambda x: T + (x - T) % P
assert all(S[x] == S[per(x)] for x in range(T, N0 + 1))
# odd rule on each odd residue class
for rho in range(1, P, 2):
    q = lambda e: per(rho + 3 * P - e) if False else T + (rho + 3 * P - e - T) % P
    assert S[q(0)] == (sum(S[q(e)] for e in (2, 10, 52)) == 1)
# two witnesses per even residue class: a in [T, T+P), S[a], S[T + (rho + 3P - a - T) % P]
W = []
for rho in range(0, P, 2):
    ws = [a for a in range(T, T + P) if S[a] and S[T + (rho + 3 * P - a - T) % P]]
    assert len(ws) >= 2
    W.append((ws[0], ws[1]))
tbl = sum(1 << m for m in range(N0) if S[m])
print(f"N0={N0}, terms below N0: {sum(S[:N0])}, min witnesses per even class: "
      f"{min(len([a for a in range(T,T+P) if S[a] and S[T+(r+3*P-a-T)%P]]) for r in range(0,P,2))}")
if len(sys.argv) > 1:
    with open(sys.argv[1], "w") as f:
        f.write("/- Generated by computations/kuca5_data.py. Do not edit. -/\nimport Mathlib\n\n")
        f.write("namespace KucaV25\n\n")
        f.write(f"/-- Bit `m` is set iff `m < {N0}` is a term of `V(2,5)`. -/\n")
        f.write(f"def tbl : ℕ := {tbl}\n\n")
        f.write("/-- Two representations `a + (m - a)` for each even residue class `m % 694`. -/\n")
        f.write("def wit : List (ℕ × ℕ) := " + str(W).replace(" ", "") + "\n\nend KucaV25\n")
