"""Export problem write-ups to the user's GitHub repository (default: main of math-conjectures).

Safety rules, enforced in code:
  * A dedicated clone under DATA_DIR is used, never the developer's working tree.
  * Only app-owned paths are written:
      - folders created by this exporter (they contain a `.mathresearchlab` marker), or
      - a single `MathResearchLab.md` file inside a folder that already belongs to the user
        (their README, Lean files and computations are never touched).
  * The only edit to a user-owned file is appending one index line to the root README's
    "## Conjectures" list, for app-created folders. Existing lines are never changed.
  * No `.lean` files are written (the repo's Lean CI builds every .lean under Conjectures/).
  * Never force-push. On a rejected push: fetch, reset the clone to origin, regenerate, retry.
"""
from __future__ import annotations

import json
import logging
import re
import subprocess
import threading
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import select

from app.config import get_settings
from app.db import session_scope
from app.models import Conjecture, Experiment, Paper, ResearchRun

log = logging.getLogger("mrl.export")
MARKER = ".mathresearchlab"
SIDE_FILE = "MathResearchLab.md"
_lock = threading.Lock()


class ExportError(Exception):
    pass


def _git(cwd: Path, *args: str, check: bool = True) -> str:
    p = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, timeout=180)
    if check and p.returncode != 0:
        raise ExportError(f"git {' '.join(args[:2])} failed: {(p.stderr or p.stdout).strip()[-500:]}")
    return p.stdout


def clone_dir() -> Path:
    return get_settings().data_dir / "repo-export"


def ensure_clone() -> Path:
    s = get_settings()
    d = clone_dir()
    if not (d / ".git").exists():
        d.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "-q", "--branch", s.repo_export_branch, s.repo_export_remote, str(d)],
                       check=True, capture_output=True, text=True, timeout=600)
    _git(d, "fetch", "-q", "origin", s.repo_export_branch)
    _git(d, "checkout", "-q", s.repo_export_branch)
    _git(d, "reset", "-q", "--hard", f"origin/{s.repo_export_branch}")  # our clone has nothing of its own
    return d


def folder_name(title: str) -> str:
    title = re.sub(r"\$[^$]*\$", " ", title)  # drop inline math, which makes unreadable names
    words = re.findall(r"[A-Za-z0-9]+", title)
    stop = {"of", "the", "a", "an", "and", "in", "on", "are", "is", "for", "to", "exactly", "with", "characterize",
            "characterization", "compute", "determine", "conjecture", "problem", "all", "every", "that", "its"}
    keep = [w for w in words if w.lower() not in stop][:4]
    return "".join(w[:1].upper() + w[1:] for w in keep)[:40] or "Problem"


def assign_folder(repo: Path, c: Conjecture) -> tuple[str, bool]:
    """Return (folder, app_owned). Respects an explicit mapping in extraction_details['repo_folder']."""
    det = c.extraction_details or {}
    if det.get("repo_folder"):
        f = det["repo_folder"]
        p = repo / "Conjectures" / f
        return f, (not p.exists()) or (p / MARKER).exists()
    base = folder_name(c.title)
    f, i = base, 2
    while (repo / "Conjectures" / f).exists() and not (repo / "Conjectures" / f / MARKER).exists():
        f = f"{base}{i}"
        i += 1
    return f, True


def _status_line(c: Conjecture) -> str:
    ap = (c.extraction_details or {}).get("autopilot", {})
    if c.status == "UNVERIFIED" and ap.get("skipped") == "likely_resolved":
        return "Likely already resolved (novelty pre-check); not researched"
    if c.status == "UNVERIFIED" and ap.get("skipped") == "trivial_or_ill_posed":
        return "Judged trivial or ill-posed (novelty pre-check); not researched"
    return {"DISPROVED": "**False**", "SOLVED": "**Solved**", "VERIFIED_OPEN": "Open (verified)",
            "LIKELY_OPEN": "Likely open", "UNVERIFIED": "Open per source; openness not yet verified",
            "SUPERSEDED": "Superseded"}.get(c.status, c.status)


def render(db, c: Conjecture, app_owned: bool) -> tuple[str, dict[str, str]]:
    """Main markdown plus extra files {relative path: content}."""
    src = db.get(Paper, c.source_paper_id) if c.source_paper_id else None
    runs = db.scalars(select(ResearchRun).where(ResearchRun.conjecture_id == c.id)
                      .order_by(ResearchRun.created_at)).all()
    exps = db.scalars(select(Experiment).where(Experiment.conjecture_id == c.id)
                      .order_by(Experiment.created_at)).all()
    extra: dict[str, str] = {}
    L = [f"# {c.title}", "",
         "<!-- Generated by MathResearchLab. This file is rewritten on every sync; edit the app, not this file. -->",
         "", f"**Status:** {_status_line(c)}", ""]
    if not app_owned:
        L[0] = f"# MathResearchLab notes: {c.title}"
        L += ["*This folder's README and Lean files are yours and are never modified. This file holds only "
              "what MathResearchLab recorded.*", ""]
    L += ["## Statement", "", "Original wording (verbatim from the source):", "", "```latex", c.original_statement, "```", ""]
    if c.normalized_statement:
        L += ["Normalized:", "", c.normalized_statement, ""]
    if src:
        L += [f"Source: {', '.join(src.authors or [])}, *{src.title}*"
              + (f", arXiv:{src.arxiv_id}" if src.arxiv_id else "") + (f", doi:{src.doi}" if src.doi else "")
              + (f", p. {c.source_page}" if c.source_page else "") + (f", {c.source_section}" if c.source_section else ""), ""]
    if c.definitions:
        L += ["## Definitions", ""] + [f"- **{d.get('term')}**: {d.get('definition')}" for d in c.definitions] + [""]
    if c.known_results:
        L += ["## Known results", ""]
        for k in c.known_results:
            L.append(f"- {k.get('statement')} *({k.get('citation') or 'no citation'}"
                     + ("; computational" if k.get("is_computational") else "")
                     + (f"; reproduced: {k.get('reproduced')}" if k.get("is_computational") else "") + ")*")
            if k.get("note"):
                L.append(f"  - {k['note']}")
        L.append("")
    det = c.extraction_details or {}
    if det.get("autopilot", {}).get("precheck"):
        pc = det["autopilot"]["precheck"]
        L += ["## Novelty pre-check", "", f"Verdict: **{pc.get('verdict')}**. {pc.get('reason', '')}", ""]
    if exps:
        L += ["## Computations", "", "Run in the MathResearchLab sandbox. Code and results are in `computations/`.", ""]
        for e in exps:
            stem = f"mrl_{e.id[:8]}"
            summ = (e.result or {}).get("summary") if isinstance(e.result, dict) else None
            L.append(f"- **{e.title}** [{e.status}, {e.result_kind.replace('_', ' ')}]"
                     + (f": {summ if isinstance(summ, str) else json.dumps(summ)[:300]}" if summ else "")
                     + f" ([code](computations/{stem}.py), [result](computations/{stem}.result.json))")
            if e.interpretation:
                L.append(f"  - {e.interpretation.strip()[:1500]}")
            extra[f"computations/{stem}.py"] = (
                f"# MathResearchLab experiment {e.id}\n# {e.title}\n# sha256(code) = {e.code_sha256}\n"
                f"# parameters: {json.dumps(e.parameters)[:2000]}\n# environment: {json.dumps(e.environment)[:800]}\n\n" + e.code)
            extra[f"computations/{stem}.result.json"] = json.dumps(
                {"status": e.status, "runtime_seconds": e.runtime_seconds, "result": e.result}, indent=1, default=str)
        L.append("")
    if runs:
        L += ["## AI research runs", "",
              "Reports from the six-agent research team. Everything in them is AI-generated and unverified unless the "
              "report lists it under *Established facts*.", ""]
        for r in runs:
            fname = f"research/{(r.created_at or datetime.now(timezone.utc)).strftime('%Y-%m-%d')}-run-{r.id[:8]}.md"
            if r.report_markdown:
                extra[fname] = r.report_markdown
            sr = (r.checkpoint or {}).get("stop_reason") or ""
            L.append(f"- [{r.created_at:%Y-%m-%d} run {r.id[:8]}]({fname}): {r.status}. {sr[:400]}")
        L.append("")
    return "\n".join(L) + "\n", extra


def _update_index(repo: Path, entries: dict[str, str]) -> bool:
    """Append missing index lines under '## Conjectures' in the root README. Never edits existing lines."""
    readme = repo / "README.md"
    if not readme.exists() or not entries:
        return False
    text = readme.read_text()
    lines = text.split("\n")
    try:
        start = next(i for i, l in enumerate(lines) if l.strip() == "## Conjectures")
    except StopIteration:
        return False
    end = start + 1
    while end < len(lines) and not lines[end].startswith("## "):
        end += 1
    last_item = max((i for i in range(start, end) if lines[i].startswith("- ")), default=start)
    changed = False
    for i, l in enumerate(lines):  # refresh the app's own lines only (they end with "(MathResearchLab)")
        for folder, line in entries.items():
            if f"(Conjectures/{folder}/)" in l and l.rstrip().endswith("(MathResearchLab)") and l != line:
                lines[i] = line
                changed = True
    text = "\n".join(lines)
    new = [line for folder, line in entries.items() if f"(Conjectures/{folder}/)" not in text]
    if new:
        lines[last_item + 1:last_item + 1] = new
        changed = True
    if changed:
        readme.write_text("\n".join(lines))
    return changed


def _app_owned_path(repo: Path, rel: str) -> bool:
    """A path is app-owned if it is the side file in a user folder or lies under a folder with our marker."""
    parts = Path(rel).parts
    if len(parts) >= 3 and parts[0] == "Conjectures" and parts[2] == SIDE_FILE:
        return True
    for i in range(2, len(parts)):
        d = "/".join(parts[:i])
        if (repo / d / MARKER).exists():
            return True
        # deleted by orphan cleanup: ownership is judged by the committed marker
        if subprocess.run(["git", "cat-file", "-e", f"HEAD:{d}/{MARKER}"], cwd=repo, capture_output=True).returncode == 0:
            return True
    return False


def _remove_orphans(repo: Path, keep: set[str]) -> None:
    """Remove app-owned material for problems no longer exported. Never touches user-owned files."""
    root = repo / "Conjectures"
    readme = repo / "README.md"
    for d in sorted(p for p in root.iterdir() if p.is_dir()) if root.exists() else []:
        if d.name in keep:
            continue
        if (d / MARKER).exists():  # a folder the app created
            _git(repo, "rm", "-r", "-q", "--ignore-unmatch", f"Conjectures/{d.name}")
            if readme.exists():
                lines = readme.read_text().split("\n")
                lines = [l for l in lines if not (f"(Conjectures/{d.name}/)" in l and l.rstrip().endswith("(MathResearchLab)"))]
                readme.write_text("\n".join(lines))
        else:  # user folder: only our side file and subfolder
            if (d / SIDE_FILE).exists():
                _git(repo, "rm", "-q", "--ignore-unmatch", f"Conjectures/{d.name}/{SIDE_FILE}")
            if (d / "MathResearchLab" / MARKER).exists():
                _git(repo, "rm", "-r", "-q", "--ignore-unmatch", f"Conjectures/{d.name}/MathResearchLab")


def sync(conjecture_ids: list[str] | None = None, *, dry_run: bool = False, force_enabled: bool = False) -> dict:
    """Write all (or the given) conjectures, commit, push. Returns a summary dict.
    dry_run: write into the clone and report the staged changes, without committing or pushing."""
    s = get_settings()
    if not (s.repo_export_enabled or force_enabled):
        return {"skipped": "REPO_EXPORT_ENABLED=false"}
    with _lock:
        last_err = None
        for attempt in range(3):
            repo = ensure_clone()
            written, index_entries = [], {}
            with session_scope() as db:
                q = select(Conjecture).order_by(Conjecture.created_at)
                if conjecture_ids:
                    q = q.where(Conjecture.id.in_(conjecture_ids))
                for c in db.scalars(q):
                    det = c.extraction_details or {}
                    if det.get("duplicate_of") or det.get("autopilot", {}).get("skipped") == "already_in_repo":
                        continue  # never duplicate a problem the repo already has
                    folder, owned = assign_folder(repo, c)
                    if (c.extraction_details or {}).get("repo_folder") != folder:
                        c.extraction_details = {**(c.extraction_details or {}), "repo_folder": folder}
                    base = repo / "Conjectures" / folder
                    base.mkdir(parents=True, exist_ok=True)
                    main_md, extra = render(db, c, owned)
                    if owned:
                        (base / MARKER).write_text("This folder is generated by MathResearchLab (platform/).\n")
                        (base / "README.md").write_text(main_md)
                        index_entries[folder] = f"- [{c.title}](Conjectures/{folder}/) — {_status_line(c)} (MathResearchLab)"
                        sub = base
                    else:
                        (base / SIDE_FILE).write_text(main_md)
                        sub = base / "MathResearchLab"  # extras for user-owned folders go in a subfolder we own
                        if extra:
                            sub.mkdir(exist_ok=True)
                            (sub / MARKER).write_text("Generated by MathResearchLab.\n")
                            main_md = main_md.replace("](computations/", "](MathResearchLab/computations/") \
                                             .replace("](research/", "](MathResearchLab/research/")
                            (base / SIDE_FILE).write_text(main_md)
                    for rel, content in extra.items():
                        assert not rel.endswith(".lean")
                        p = sub / rel
                        p.parent.mkdir(parents=True, exist_ok=True)
                        p.write_text(content)
                    written.append(folder)
            if not conjecture_ids:
                _remove_orphans(repo, set(written))
            _update_index(repo, index_entries)
            _git(repo, "add", "-A", "Conjectures", "README.md")
            if not _git(repo, "status", "--porcelain").strip():
                return {"pushed": False, "reason": "no changes", "folders": written}
            changed = _git(repo, "diff", "--cached", "--name-only").split()
            bad = [p for p in changed if p.endswith(".lean")]
            if bad:
                raise ExportError(f"refusing to commit Lean files: {bad}")
            modified = _git(repo, "diff", "--cached", "--name-only", "--diff-filter=MD").split()
            foreign = [p for p in modified if p != "README.md" and not _app_owned_path(repo, p)]
            if foreign:
                raise ExportError(f"refusing to modify files the app does not own: {foreign[:5]}")
            if dry_run:
                stat = _git(repo, "diff", "--cached", "--stat")
                _git(repo, "reset", "-q", "--hard", f"origin/{s.repo_export_branch}")
                return {"dry_run": True, "files": changed, "modified_existing": modified, "stat": stat, "folders": written}
            _git(repo, "-c", "user.name=MathResearchLab", "-c", f"user.email={s.repo_export_author_email or 'mathresearchlab@users.noreply.github.com'}",
                 "commit", "-q", "-m", f"MathResearchLab: update {', '.join(sorted(set(written)))[:200]}\n\n"
                 "Automated sync of problem write-ups, research reports and sandbox computations.")
            p = subprocess.run(["git", "push", "-q", "origin", f"HEAD:{s.repo_export_branch}"], cwd=repo,
                               capture_output=True, text=True, timeout=300)
            if p.returncode == 0:
                sha = _git(repo, "rev-parse", "--short", "HEAD").strip()
                log.info("exported %d folder(s) to %s (%s)", len(written), s.repo_export_branch, sha)
                return {"pushed": True, "commit": sha, "files": changed, "folders": written}
            last_err = (p.stderr or p.stdout).strip()
            log.warning("push rejected (attempt %d): %s", attempt + 1, last_err[-300:])
        raise ExportError(f"push failed after retries: {last_err[-500:] if last_err else ''}")
